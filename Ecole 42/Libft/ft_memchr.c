#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	char	*ps;

	ps = (char *) s;
	size_t	i;

	i = 0;
	while (i < n)
	{
		if (ps[i] == (char) c)
		{
			return (&ps[i]);
		}
		i++;
	}
	return (NULL);
}
