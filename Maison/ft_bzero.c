#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	unsigned char	*ps;

	ps = (unsigned char *) s;
	size_t	i;

	i = 0;
	while (i < n)
	{
		ps[i] = 0;
		i++;
	}
}
