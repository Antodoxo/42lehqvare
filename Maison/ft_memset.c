#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	*ps;

	ps = (unsigned char *) s;
	size_t	i;

	i = 0;
	while (i < n)
	{
		*ps++ = c;
		i++;
	}
	return (s);
}
